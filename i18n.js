class I18nEngine {
  constructor() {
    this.currentLang = localStorage.getItem('orbit_lang') || (navigator.language.startsWith('tr') ? 'tr' : 'en');
  }

  init() {
    const selectElements = document.querySelectorAll('.lang-select-box, #lang-select');
    selectElements.forEach(selectEl => {
      selectEl.value = this.currentLang;
      selectEl.addEventListener('change', (e) => this.setLanguage(e.target.value));
    });

    // Listen for storage changes across tabs
    window.addEventListener('storage', (e) => {
      if (e.key === 'orbit_lang' && e.newValue && e.newValue !== this.currentLang) {
        this.setLanguage(e.newValue, false);
      }
    });

    this.apply();
  }

  setLanguage(lang, save = true) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    this.currentLang = lang;
    if (save) {
      localStorage.setItem('orbit_lang', lang);
    }
    document.documentElement.lang = lang;

    // Update all language select dropdowns on the page
    document.querySelectorAll('.lang-select-box, #lang-select').forEach(selectEl => {
      selectEl.value = lang;
    });

    this.apply();
    
    // Dispatch global custom event for dynamic JS scripts
    const event = new CustomEvent('orbit:lang-changed', {
      detail: { lang, dict: TRANSLATIONS[lang] }
    });
    document.dispatchEvent(event);

    if (window.orbitSynthBeep) window.orbitSynthBeep(880, 0.05);
  }

  t(key, fallback = '') {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS['en'];
    return dict[key] || fallback || key;
  }

  apply() {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS['en'];
    
    // Inner text translation
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
        if (el.hasAttribute('data-text')) {
          el.setAttribute('data-text', dict[key]);
        }
      }
    });

    // Placeholder attribute translation
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    // Title attribute translation
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.title = dict[key];
      }
    });

    // HTML content translation
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });
  }
}

window.i18nEngine = new I18nEngine();
