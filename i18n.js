/* ─── INTERNATIONALIZATION ENGINE ─── */
class I18nEngine {
  constructor() {
    this.currentLang = localStorage.getItem('orbit_lang') || 'tr';
  }

  init() {
    this.setLanguage(this.currentLang);
    this.bindEvents();
  }

  bindEvents() {
    document.querySelectorAll('.lang-select-box').forEach(select => {
      select.value = this.currentLang;
      select.addEventListener('change', (e) => {
        this.setLanguage(e.target.value);
      });
    });
  }

  setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'tr';
    this.currentLang = lang;
    localStorage.setItem('orbit_lang', lang);

    // Sync all dropdowns
    document.querySelectorAll('.lang-select-box').forEach(select => {
      select.value = lang;
    });

    const dict = TRANSLATIONS[lang];
    if (!dict) return;

    // 1. Elements with data-i18n (updates innerHTML or textContent depending on HTML presence)
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        if (dict[key].includes('<') && dict[key].includes('>')) {
          el.innerHTML = dict[key];
        } else if (el.children.length === 0) {
          el.textContent = dict[key];
        } else {
          // If element has structural children (icons, badges, etc.) preserve text node or update safely
          const firstTextNode = Array.from(el.childNodes).find(n => n.nodeType === Node.TEXT_NODE);
          if (firstTextNode) {
            firstTextNode.textContent = dict[key];
          } else {
            el.innerHTML = dict[key];
          }
        }
      }
    });

    // 2. Elements explicitly marked with data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    // 3. Input placeholders with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] !== undefined) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // 4. Titles with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key] !== undefined) {
        el.setAttribute('title', dict[key]);
      }
    });

    // 5. Glitch titles data-text attributes
    document.querySelectorAll('.glitch-title[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.setAttribute('data-text', dict[key]);
      }
    });

    // Broadcast custom lang change event so app.js can re-render dynamic components
    document.dispatchEvent(new CustomEvent('orbit:lang-changed', {
      detail: { lang, dict }
    }));
  }

  t(key, fallback = '') {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS['tr'];
    return dict[key] || fallback || key;
  }
}

